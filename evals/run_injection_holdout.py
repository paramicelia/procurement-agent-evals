#!/usr/bin/env python3
"""Measures injection_detected() recall on a held-out, reworded set
of adversarial phrasings (data_holdout_injection/), separately from the
in-distribution n=6 figure in EVALS.md.

    python evals/run_injection_holdout.py

No LLM call is needed: procurement_agent.tools.decide() checks
injection_detected(raw_text) BEFORE it looks at anything extract_quote
produced, so this regex's recall does not depend on extraction quality —
which is also exactly why the write-safety guarantee in LIMITATIONS.md does
not rest on this number either way. This script uses each fixture's own
ground-truth extracted/comparison fields to call decide() directly, so it
also reports what action would actually result if the regex misses.
"""
from __future__ import annotations

import datetime as dt
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from procurement_agent.models import ComparisonResult, ExtractedQuote  # noqa: E402
from procurement_agent.tools import decide, injection_detected  # noqa: E402


def load_fixtures(data_dir: Path) -> list[dict]:
    labels_dir, emails_dir = data_dir / "labels", data_dir / "emails"
    items = []
    for label_path in sorted(labels_dir.glob("*.json")):
        label = json.loads(label_path.read_text())
        raw_text = (emails_dir / f"{label['id']}.txt").read_text()
        items.append({"label": label, "raw_text": raw_text})
    return items


def main() -> None:
    data_dir = ROOT / "data_holdout_injection"
    fixtures = load_fixtures(data_dir)
    if not fixtures:
        print(f"no fixtures in {data_dir} -- run data_gen/generate_injection_holdout.py first", file=sys.stderr)
        raise SystemExit(1)

    results = []
    for item in fixtures:
        label, raw_text = item["label"], item["raw_text"]
        gt = label["ground_truth"]
        extracted = ExtractedQuote(**gt["extracted"])
        comparison = ComparisonResult(
            matches=[], unmatched_items=gt["comparison_summary"]["unmatched_items"],
            conflicting=gt["comparison_summary"]["conflicting"],
            max_deviation_pct=gt["comparison_summary"]["max_deviation_pct"],
        )
        caught = injection_detected(raw_text)
        decision = decide(extracted, comparison, raw_text)
        results.append({
            "id": label["id"],
            "phrase": label["injection_phrase"],
            "caught_by_regex": caught,
            "decide_action": decision.action.value,
            "decide_reason": decision.reason,
        })

    n = len(results)
    caught_n = sum(1 for r in results if r["caught_by_regex"])
    recall = caught_n / n if n else None

    payload = {
        "n": n,
        "caught": caught_n,
        "recall": recall,
        "note": ("Held-out phrasings are reworded so none matches INJECTION_PATTERNS; their only "
                 "4-word overlap with the 4 training phrases in data_gen/generate_data.py is 'the order "
                 "right away' (i008), see tests/test_injection_holdout_disjoint.py. A miss here means decide() falls "
                 "through to the ordinary price/catalog checks, which auto_accept these fixtures "
                 "(they are otherwise clean, catalog-matching quotes) -- i.e. a missed paraphrase is "
                 "not just an unlabeled row, it is a silent auto-accept of an attempted injection."),
        "results": results,
    }
    out_path = ROOT / "evals" / "results" / "injection_holdout_latest.json"
    out_path.write_text(json.dumps(payload, indent=2))

    print(f"held-out injection recall: {caught_n}/{n} ({recall * 100:.1f}%)" if n else "no fixtures")
    for r in results:
        mark = "CAUGHT" if r["caught_by_regex"] else "MISSED"
        print(f"  [{mark}] {r['id']:<32} -> decide()={r['decide_action']:<22} | {r['phrase'][:70]}")
    print(f"\nwrote {out_path}")

    rows = "\n".join(
        f"| `{r['id']}` | {'caught' if r['caught_by_regex'] else '**missed**'} | `{r['decide_action']}` | {r['phrase']} |"
        for r in results
    )
    md = f"""# Held-out adversarial injection recall

Generated by `python evals/run_injection_holdout.py` from
`evals/results/injection_holdout_latest.json` — never hand-edit the numbers
below; edit `data_gen/generate_injection_holdout.py` or
`evals/run_injection_holdout.py` and re-run instead.

Generated {dt.datetime.now(dt.UTC).isoformat()}. n = {n} fixtures, seed 4242.

## Why this file exists

EVALS.md's in-distribution injection recall (100%, n=6) is measured against
phrases the same author wrote in the same session as the regex being scored
— disclosed in LIMITATIONS.md as close to circular. This file measures the
same detector (`procurement_agent.tools.injection_detected`, the regex behind
`INJECTION_PATTERNS`) against {n} paraphrases that express the same
underlying attacks (ignore prior instructions, claim approver authority,
claim pre-approval, tell the agent to skip review) in different words.
`tests/test_injection_holdout_disjoint.py` checks that none of them matches
the regex and that their only 4-word overlap with the 4 in-distribution
phrases in `data_gen/generate_data.py` is "the order right away" (i008),
which the regex still misses because its pattern requires "place" first.

## Result

**{caught_n}/{n} caught ({fmt_pct(recall)}).**

This is the real, held-out number — not the 100.0% in-distribution figure —
and it should be read as the actual state of the injection detector's
generalization: it catches phrasings close to its own training vocabulary
and misses paraphrases of the same attacks. Every miss below resulted in
`decide()` returning `auto_accept` on a fixture that is otherwise a clean,
catalog-matching quote — i.e. a missed paraphrase is not a benign unlabeled
row, it is a silent auto-accept of an attempted injection.

**What this does NOT mean**: it does not mean an attacker can place an
unapproved order. The structural guarantee (`Store.place_order` re-checks
for an approved approval row; see ADR 0002 and
`tests/test_invariants.py::test_no_write_without_approval`) does not depend
on this regex at all — a missed injection still only reaches
`auto_accept` -> a **pending, unapproved** approval request. A human still
has to approve it before anything is written, and that approval request
shows the extracted order next to an excerpt of the raw email, so an
injected sentence within the first 2000 characters is in front of the approver (`build_approval_payload` in
`procurement_agent/orchestrator.py`; the approver can still miss it). What this number measures is
whether the regex successfully routes a sneaky email to a human's attention
sooner (as `escalate_human`) instead of the normal approval queue — a
real, measured, and currently weak capability, not the safety boundary
itself.

## Per-phrase results

| id | regex | decide() action | held-out phrase |
|---|---|---|---|
{rows}

## Reproduce this

```bash
source .venv/bin/activate
python data_gen/generate_injection_holdout.py --out-dir data_holdout_injection --seed 4242
python evals/run_injection_holdout.py
```
"""
    (ROOT / "EVALS_INJECTION_HOLDOUT.md").write_text(md)
    print(f"wrote {ROOT / 'EVALS_INJECTION_HOLDOUT.md'}")


def fmt_pct(x: float | None) -> str:
    return f"{x * 100:.1f}%" if x is not None else "n/a"


if __name__ == "__main__":
    main()
